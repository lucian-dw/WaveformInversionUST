function benchmark_native_production(binaryPath,outputDir)
% Representative computational size; numerical phantom, not an anatomy benchmark.
root=fileparts(fileparts(mfilename('fullpath')));addpath(fullfile(root,'matlab'));
assert(~exist(outputDir,'dir'),'Use a fresh directory');mkdir(outputDir);
n=1004;x=linspace(-.12,.12,n);y=x;[X,Y]=meshgrid(x,y);dx=x(2)-x(1);
c=1500+30*exp(-((X-.02).^2+(Y+.01).^2)/.0005)-20*exp(-((X+.03).^2+(Y-.02).^2)/.0002);
theta=(0:127)*2*pi/128;cx=round((.11*cos(theta)-x(1))/dx)+1;cy=round((.11*sin(theta)-y(1))/dx)+1;
indices=sub2ind(size(c),cy,cx).';assert(numel(unique(indices))==128);
dt=.3*dx/1550;nt=ceil(220e-6/dt);t=(0:nt-1)*dt;
model=struct('c_mps',c,'x_m',x,'y_m',y,'tx_index',indices,'rx_index',indices, ...
    'dt_s',dt,'source_pressure',sin(2*pi*1e6*t).*exp(-((t-3e-6)/.7e-6).^2));
cfg=struct('backend','native128','pml_size',10,'density_kg_m3',1000, ...
    'sound_speed_ref_mps',1550,'downsample_factor',2,'time_offset_s',-3e-6, ...
    'work_dir',outputDir,'binary_path',binaryPath,'device_num',0);
rf=wust_simulate(model,cfg);assert(all(isfinite(rf.pressure(:))));
prep=struct('frequencies_hz',(.3:.025:1)*1e6,'x_m',x,'y_m',y,'c_geom_mps',1500, ...
    'window','none','phase_correction','none','mask',~eye(128));
prep.data_units='Pa*s';prep.measurement_provenance='self_simulated';
timer=tic;obs=wust_prepare(rf,prep);prepare_seconds=toc(timer);
timer=tic;save(fullfile(outputDir,'rf.mat'),'rf','-v7.3');save_seconds=toc(timer);
save(fullfile(outputDir,'observations.mat'),'obs','-v7.3');
report=struct('grid_including_pml',[1024,1024],'transmitters',128,'time_steps',nt, ...
    'dt_s',dt,'generation_seconds',rf.simulation.generation_seconds, ...
    'fir_seconds',rf.simulation.filter_seconds,'prepare_seconds',prepare_seconds, ...
    'rf_save_seconds',save_seconds,'rf_shape',size(rf.pressure), ...
    'frequency_shape',size(obs.Y),'finite',all(isfinite(obs.Y(:))), ...
    'note','Representative production computational grid, artificial numerical medium; not anatomical accuracy or speedup benchmark');
fid=fopen(fullfile(outputDir,'report.json'),'w');fprintf(fid,'%s',jsonencode(report));fclose(fid);disp(report);
end
